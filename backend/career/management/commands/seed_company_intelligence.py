class Command(BaseCommand):
    help = 'Seeds verified Global & India-First Company Intelligence and authentic vacancies.'

    def handle(self, *args, **options):
        self.stdout.write("Seeding verified Global & India-First Company Discovery database...")
        now = timezone.now()
        created_count = 0
        updated_count = 0

        for item in COMPREHENSIVE_COMPANIES:
            comp, created = Company.objects.update_or_create(
                slug=item['slug'],
                defaults={
                    'company_name': item['company_name'],
                    'canonical_name': item['canonical_name'],
                    'domain': item['domain'],
                    'website': item['website'],
                    'careers_url': item['careers_url'],
                    'industry': item['industry'],
                    'description': item['description'],
                    'founded_year': item['founded_year'],
                    'founding_location': item['founding_location'],
                    'headquarters': item['headquarters'],
                    'country': item['country'],
                    'region': item['region'],
                    'company_stage': item['company_stage'],
                    'company_size': item['company_size'],
                    'is_startup': item['is_startup'],
                    'office_locations': item['office_locations'],
                    'locations': item['office_locations'],
                    'countries_of_operation': item['countries_of_operation'],
                    'products_and_services': item['products_and_services'],
                    'departments': item['departments'],
                    'job_source_type': item['job_source_type'],
                    'job_source_token': item['job_source_token'],
                    'data_source': item['data_source'],
                    'source_url': item['source_url'],
                    'last_verified_at': now,
                    'verification_status': 'verified',
                }
            )
            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(self.style.SUCCESS(
            f"Seeded {created_count} new companies, updated {updated_count}. Total in DB: {Company.objects.count()}"
        ))

        # Seed verified live opportunities
        jobs_created = 0
        jobs_updated = 0
        for job_data in VERIFIED_ADDITIONAL_JOBS:
            comp = Company.objects.filter(company_name__iexact=job_data['company_name']).first()
            posting, j_created = JobPosting.objects.update_or_create(
                source_name='direct_careers',
                external_id=job_data['external_id'],
                defaults={
                    'company': comp,
                    'company_name': job_data['company_name'],
                    'title': job_data['title'],
                    'description': job_data['description'],
                    'location': job_data['location'],
                    'workplace_type': job_data['workplace_type'],
                    'employment_type': job_data['employment_type'],
                    'experience_level': job_data['experience_level'],
                    'required_skills': job_data['required_skills'],
                    'application_url': job_data['application_url'],
                    'posted_at': now,
                    'verification_status': 'verified_active',
                }
            )
            if j_created:
                jobs_created += 1
            else:
                jobs_updated += 1

        self.stdout.write(self.style.SUCCESS(
            f"Seeded jobs: {jobs_created} created, {jobs_updated} updated. Total active jobs in catalog: {JobPosting.objects.filter(verification_status='verified_active').count()}"
        ))
